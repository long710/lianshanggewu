/**
 * 以太坊地址生成全流程演示 (The Web3 课程)
 * 流程：熵 -> 助记词 -> 种子 -> 私钥 -> 公钥 -> 地址
 */

const bip39 = require('bip39');
const { ethers } = require('ethers');
const crypto = require('crypto');

function generateAccount() {
    console.log("========== 第一阶段：从虚无到存在 (Account Generation) ==========\n");

    // ------------------------------------------------------------------
    // 1. 熵 (Entropy) - 一切的起源
    // ------------------------------------------------------------------
    // 原理：生成一个 128位 (16字节) 或 256位 (32字节) 的真随机数。
    // 16字节 = 12个助记词；32字节 = 24个助记词。
    // 这里我们用 Node.js 自带的 crypto 库来模拟“上帝掷骰子”。
    const entropy = crypto.randomBytes(16);

    // console.log("1. [熵 (Entropy)]");
    // console.log("   说明: 这是计算机生成的纯粹混乱，账户的灵魂。");
    // console.log(`   Hex : 0x${entropy.toString('hex')}`);
    // console.log("------------------------------------------------------------------");

    // ------------------------------------------------------------------
    // 2. 助记词 (Mnemonic) - 人类可读的备份
    // ------------------------------------------------------------------
    // 原理：BIP-39 标准。将上面的随机数映射到 2048 个单词表中。
    // 步骤：熵 -> 添加校验和 -> 切割 -> 查表 -> 助记词。
    const mnemonic = 'wife way upgrade release scout receive filp harbor story ski damage cereal'//bip39.entropyToMnemonic(entropy);

    // console.log("2. [助记词 (Mnemonic)]");
    // console.log("   说明: 熵的另一种表现形式，方便人类记忆和抄写。");
    // console.log(`   词组: ${mnemonic}`);
    // console.log("------------------------------------------------------------------");

    // ------------------------------------------------------------------
    // 3. 种子 (Seed) - 确定性的根
    // ------------------------------------------------------------------
    // 原理：使用 PBKDF2 算法，将助记词加盐 (默认为 "mnemonic") 进行 2048 次哈希运算。
    // 结果：生成一个 512位 (64字节) 的二进制种子。
    // 注意：这里是同步方法，实际开发中为了不阻塞主线程通常用异步。
    const seed = bip39.mnemonicToSeedSync(mnemonic);

    // console.log("3. [种子 (Seed)]");
    // console.log("   说明: 助记词经过哈希搅拌后的产物，是 HD 钱包的根密钥。");
    // console.log(`   Hex : 0x${seed.toString('hex').substring(0, 64)}... (太长了只显示前64位)`);
    // console.log("------------------------------------------------------------------");

    // ------------------------------------------------------------------
    // 4. 根节点与路径推导 (Derivation)
    // ------------------------------------------------------------------
    // 原理：从种子生成主扩展密钥 (Master Key)，然后按照路径切分出具体的私钥。
    // 路径 m/44'/60'/0'/0/0 解释：
    // m: 根节点
    // 44': BIP-44 标准
    // 60': 以太坊的代号 (比特币是 0')
    // 0': 账户索引 0
    // 0: 外部链 (收款用)
    // 0: 第 0 个地址

    // 使用 ethers 创建 HD 钱包节点
    const hdNode = ethers.HDNodeWallet.fromSeed(seed);

    // 遍历 index 1-100，打印地址和私钥
    console.log("========== 批量生成地址 (Index 1-100) ==========\n");

    for (let i = 5300; i <= 6300; i++) {
        // 按照以太坊标准路径推导，修改最后的索引
        const derivationPath = `m/44'/60'/0'/0/${i}`;
        const wallet = hdNode.derivePath(derivationPath);

        // 打印格式：地址:私钥
        console.log(`'${wallet.address}',`);
    }

    console.log("\n==================================================================");
    console.log("总结：已生成 100 个地址及其对应的私钥。");
}
//
// 执行函数
generateAccount();
